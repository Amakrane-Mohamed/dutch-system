# Regenerates src/content/videos.ts from the oEmbed-verified lists in /workspace/ytde.
# Only rows with HTTP 200 are used. Rows from verified_ar*.txt are Arabic-taught (arabic: true).
import json, os, glob
D = '/workspace/ytde'
rows, seen = [], set()
def add(path, arabic):
    for line in open(path, encoding='utf-8'):
        p = line.rstrip('\n').split('|')
        if len(p) < 5 or p[2] != '200' or p[1] in seen: continue
        seen.add(p[1]); rows.append((p[0], p[1], p[3].strip(), p[4].strip(), arabic))
for f in sorted(glob.glob(f'{D}/verified_ar*.txt')): add(f, True)
add(f'{D}/verified.txt', False)
# Arabic playlists found in verified.txt (Shehata) are Arabic-taught too
AR_CH = ('Shehata', 'German with Badr', 'German Training Center', 'Ahmad Yaghi', 'Deutsch mit Mira')
out = ["// Generated by scripts/make_videos.py. Every id returned HTTP 200 from YouTube oEmbed (checked 11 Nov 2026).",
       "// arabic: true = German explained in Arabic or Darija.",
       "export interface Video { id: string; kind: 'video' | 'playlist'; title: string; channel: string; arabic?: boolean }",
       "export const VIDEOS: Record<string, Video> = {"]
for k, i, ch, t, ar in rows:
    ar = ar or any(c in ch for c in AR_CH)
    out.append(f"  {json.dumps(i)}: {{ id: {json.dumps(i)}, kind: '{'video' if k == 'v' else 'playlist'}', title: {json.dumps(t, ensure_ascii=False)}, channel: {json.dumps(ch, ensure_ascii=False)}{', arabic: true' if ar else ''} }},")
out += ["}",
        "export const embedUrl = (v: Video) => v.kind === 'video' ? `https://www.youtube-nocookie.com/embed/${v.id}?rel=0` : `https://www.youtube-nocookie.com/embed/videoseries?list=${v.id}&rel=0`",
        "export const watchUrl = (v: Video) => v.kind === 'video' ? `https://www.youtube.com/watch?v=${v.id}` : `https://www.youtube.com/playlist?list=${v.id}`", ""]
open('/workspace/german-system/src/content/videos.ts', 'w', encoding='utf-8').write('\n'.join(out))
print(len(rows), sum(1 for r in rows if r[4] or any(c in r[2] for c in AR_CH)), 'arabic')
